/**
 * observe.js — `media_observe`: the page model, i.e. the agent's eyes.
 *
 * `session.snapshot` returns a compact, stable list of `ref → {role, text, selector}`; the `ref` is the
 * affordance that makes agent-driven recording work (SPEC §2.2). This module renders it as readable
 * lines first, because the model picks its next action from those lines.
 *
 * @module media-publish/tools/observe
 */
import { defineTool } from '../tool-kit.js';
import {
  TIMEOUT, argumentFailure, failure, renderEnvelope, success,
} from './common.js';

/** How many `ref` lines to spell out before deferring to the JSON payload. */
const MAX_RENDERED_ELEMENTS = 80;

/**
 * @param {any} ctx
 * @param {{ engine: any, settings: Record<string, any>, dataDir: string, python: Record<string, any>,
 *           pluginRoot: string, handoffs?: any }} deps
 */
export function register(ctx, deps) {
  const { engine, handoffs } = deps;

  ctx.tools.register(defineTool({
    name: 'media_observe',
    description:
      'Read the current page model of a live session: URL, title, active frame, alerts (captcha / QR-login / '
      + 'risk-control heuristics found in the page text or an iframe URL), a compact list of interactive '
      + 'elements as `ref  role  "text"  selector`, a text sample, and the path of a fresh screenshot you can '
      + 'look at. This is the agent\'s EYES while recording: run it, pick the ref of the element you want, then '
      + 'call media_act with {target:{ref:"e12"}}. Refs are regenerated by every snapshot and stay valid only '
      + 'until the next one, so re-observe after anything that navigates, opens a dialog or re-renders. '
      + 'fullPage:true adds a full-page screenshot on top of the viewport one (slower on long editors).',
    parameters: {
      sessionId: { type: 'string', required: true, description: 'A live session from media_session {op:"open"}.' },
      fullPage: { type: 'boolean', description: 'Also capture a full-page screenshot and return its path.' },
      includeText: { type: 'boolean', description: 'Include the page text sample (default true); false is slightly cheaper.' },
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: true,
        properties: {
          ok: { type: 'boolean', required: true },
          method: { type: 'string' },
          summary: { type: 'string' },
          data: { type: 'object', additionalProperties: true },
          warnings: { type: 'array', items: { type: 'string' } },
          handoff: { type: 'object', additionalProperties: true },
          error: { type: 'object', additionalProperties: true },
          nextSteps: { type: 'array', items: { type: 'string' } },
        },
      },
      render: (_args, value) => renderEnvelope(
        value.ok
          ? `media_observe — ${value.data?.url ?? '?'}`
          : `media_observe — failed (${value.error?.code ?? 'ERROR'})`,
        value,
        renderLines(value),
      ),
    },
    async execute(args) {
      const method = 'session.snapshot';
      const sessionId = String(args.sessionId ?? '').trim();
      const base = { tool: 'media_observe', op: null, method, sessionId, accountCode: null, handoffs };
      if (!sessionId) {
        return argumentFailure({
          ...base,
          message: 'media_observe needs "sessionId"',
          nextSteps: ['media_session {op:"list"} to find a live session.'],
        });
      }

      try {
        const snapshot = await engine.call(method, {
          sessionId,
          includeText: args.includeText === undefined ? true : args.includeText === true,
        }, { timeoutMs: TIMEOUT.OBSERVE_MS });

        let screenshot = snapshot?.screenshot ?? null;
        let fullScreenshot = null;
        if (args.fullPage === true) {
          try {
            const shot = await engine.call('session.screenshot', { sessionId, fullPage: true, label: 'full' },
              { timeoutMs: TIMEOUT.OBSERVE_MS });
            fullScreenshot = shot?.path ?? null;
          } catch (error) {
            // A missing full-page shot must not lose the snapshot the agent just paid for.
            return success({
              ...base,
              summary: `${snapshot?.url ?? '?'} — "${snapshot?.title ?? ''}" (${snapshot?.counts?.interactive ?? 0} interactive elements)`,
              data: { ...snapshot, fullPageScreenshot: null },
              warnings: [`full-page screenshot failed: ${error?.code ?? 'ERROR'}: ${error?.message ?? error}`],
              nextSteps: [`media_act {sessionId:"${sessionId}", action:{type:"scroll", deltaY:2000}} then observe again.`],
            });
          }
        }

        const alerts = snapshot?.alerts ?? [];
        return success({
          ...base,
          summary: `${snapshot?.url ?? '?'} — "${snapshot?.title ?? ''}" (${snapshot?.counts?.interactive ?? 0} interactive elements`
            + `${snapshot?.truncated ? ', TRUNCATED at maxElements' : ''})${alerts.length ? ` — ALERTS: ${alerts.join(', ')}` : ''}`,
          data: { ...snapshot, fullPageScreenshot: fullScreenshot, screenshot: fullScreenshot ?? screenshot },
          nextSteps: alerts.length
            ? [
              `Possible captcha / login / risk-control blocker (${alerts.join(', ')}): call media_session {op:"handoff", sessionId:"${sessionId}", reason:"captcha"} and let a human finish it, then {op:"resume"}.`,
              'Do not keep clicking through a captcha page: it deepens the risk-control score.',
            ]
            : [
              `Pick a ref above and call media_act {sessionId:"${sessionId}", action:{type:"click", target:{ref:"eN"}}}.`,
              'After a navigation or re-render, call media_observe again before reusing a ref.',
            ],
        });
      } catch (error) {
        return failure(error, { ...base, method });
      }
    },
    presentCall: (args) => ({ card: 'generic', title: `media_observe ${args?.sessionId ?? ''}`.trim(), kind: 'other' }),
  }));
}

/**
 * The readable half: url/title, alerts, screenshot path and the `ref → role/text` list.
 * @param {any} value
 * @returns {string[]}
 */
function renderLines(value) {
  if (!value?.ok || !value.data) return [];
  const data = value.data;
  /** @type {string[]} */
  const lines = [
    `url: ${data.url ?? '?'}`,
    `title: ${data.title ?? ''}`,
    `activeFrame: ${data.activeFrame ?? 'main'}${Array.isArray(data.frames) && data.frames.length > 1 ? ` (frames: ${data.frames.map((f) => f.path).join(', ')})` : ''}`,
  ];
  if (data.alerts?.length) lines.push(`ALERTS: ${data.alerts.join(', ')}`);
  lines.push(`screenshot: ${data.screenshot ?? '(none)'}`);
  if (data.fullPageScreenshot) lines.push(`fullPageScreenshot: ${data.fullPageScreenshot}`);
  const elements = data.interactive ?? [];
  lines.push(`elements (${elements.length}${data.truncated ? ', truncated' : ''}) — ref  role  "text"  selector:`);
  for (const el of elements.slice(0, MAX_RENDERED_ELEMENTS)) {
    const flags = [el.visible === false ? 'hidden' : '', el.enabled === false ? 'disabled' : '', el.inFrame && el.inFrame !== 'main' ? el.inFrame : '']
      .filter(Boolean).join(',');
    lines.push(`  ${el.ref}  ${el.role || el.tag}${el.type ? `[${el.type}]` : ''}  ${el.text ? `"${String(el.text).replace(/\s+/g, ' ').slice(0, 70)}"` : '""'}`
      + `  ${el.selector ?? ''}${flags ? `  (${flags})` : ''}${el.likelySubmit ? '  <-- likely submit' : ''}`);
  }
  if (elements.length > MAX_RENDERED_ELEMENTS) {
    lines.push(`  … ${elements.length - MAX_RENDERED_ELEMENTS} more in the JSON payload below`);
  }
  if (data.textSample?.length) lines.push(`text: ${data.textSample.slice(0, 12).map((t) => `"${t}"`).join(' ')}`);
  return lines;
}
